"""ShadowPlay Notifier 를 이루는 구성 요소들입니다.

역할별로 나누어 두었습니다.

- ``paths``   : 설정과 로그 파일의 위치, 로그 기록, 전역 예외 처리
- ``config``  : config.json 읽기와 쓰기, 명령줄 인자 해석, 최종 설정 조립
- ``instance``: 뮤텍스로 중복 실행을 막고, 이미 떠 있는 창을 앞으로 끌어오기
- ``tray``    : Windows 알림 영역, 창 복원·설정·자동 실행·종료 메뉴
- ``startup`` : 현재 사용자 계정의 로그인 자동 실행 등록과 해제
- ``scan``    : 폴더를 훑어 파일 크기를 모으는 일, 파일이 열려 있는지 확인,
  표시용 단위 변환
- ``watcher`` : 녹화 시작과 중단을 판정하는 상태 기계와 감시 스레드
- ``display`` : DPI 인식, 모니터 좌표 계산, 창을 놓을 자리 결정
- ``theme``   : 창 크기와 색, 글꼴 고르기
- ``fonts``   : 함께 묶어 온 글꼴을 이 프로그램에서만 쓰도록 등록
- ``text``    : 화면에 넣기 좋게 문자열을 다듬는 일
- ``icons``   : 배너에 쓰는 아이콘(Fluent UI System Icons 를 PNG 로 구운 것)
- ``app``     : 본 창의 화면 구성과 갱신, 두 화면 사이의 전환
- ``settings_dialog`` : 환경설정 창

녹화를 기다리는 동안 띄우는 월페이퍼 화면은 아래 모듈들이 맡습니다.

- ``wallpaper``     : 월페이퍼 화면의 구성과 갱신
- ``sky``           : 시간대와 날씨에 따른 배경색과 하늘 굽기
- ``atmosphere``    : 별, 유리 위 물방울, 눈과 유성의 간헐적 연출
- ``audio``         : 스피커로 나가는 소리를 12대역 주파수 막대로
- ``imaging``       : GDI+ 로 그림을 풀고 늘려 Tk 가 읽는 형식으로
- ``nowplaying``    : 재생 중인 곡과 앨범 커버
- ``weather``       : Open-Meteo 에서 받아 오는 날씨
- ``weather_icons`` : 날씨 아이콘(Fluent UI System Icons 의 SVG)
"""
