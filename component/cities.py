def fold(text):
    """찾기 쉽도록 이름을 다듬습니다.

    악센트를 떼어 내므로 ``Segu`` 로 ``Séguéla`` 를, ``Sao`` 로 ``São`` 를
    찾을 수 있습니다. 한글은 자모로 풀었다가 다시 모아 원래대로 둡니다.
    """
    bare = "".join(c for c in unicodedata.normalize("NFD", text or "")
                   if not unicodedata.combining(c))
    return unicodedata.normalize("NFC", bare).casefold()


def match(prefix, limit=8):
    """앞글자가 맞는 도시를 찾습니다. 영문과 한국어 이름을 모두 봅니다.

    ``Seo`` 로 ``Seoul`` 이, ``서`` 로 ``서울`` 과 ``서귀포`` 가 나옵니다.
    앞에서부터 맞는 것을 먼저 놓고 그다음에 이름 가운데가 맞는 것을 놓아,
    ``York`` 처럼 뒷말만 적어도 찾을 수 있게 했습니다.
    """
    key = fold((prefix or "").strip())
    if not key:
        return []
    heads, tails = [], []
    for row in CITIES:
        names = [fold(n) for n in row[:2] if n]
        if any(n.startswith(key) for n in names):
            heads.append(row)
        elif any(key in n for n in names):
            tails.append(row)
    return (heads + tails)[:limit]


def find(name):
    """저장된 이름과 똑같은 도시를 찾습니다. 없으면 ``None`` 입니다."""
    key = fold((name or "").strip())
    for row in CITIES:
        if key and key in (fold(row[0]), fold(row[1])):
            return row
    return None


def label(name, country=""):
    """목록에 적는 한 줄입니다."""
    return "%s, %s" % (name, country) if country else name
